#!/usr/bin/env zx
/**
 * Scans assets/miniapps/ for *.zip bundles and generates
 * src/generated/bundledMiniapps.ts with one literal `require()` per zip. Metro
 * can only bundle assets referenced by a static string-literal require(), so
 * this codegen keeps that list in sync with the directory instead of requiring
 * a manual edit per bundle.
 *
 * Runs automatically from setBuildEnv() (so every build/run script regenerates
 * it), or by hand:
 *   bun run generate-bundled-miniapps
 */
import {createHash, createPublicKey, verify} from "crypto"
import {readdir, readFile, writeFile, mkdir} from "fs/promises"
import JSZip from "jszip"
import path from "path"
import {fileURLToPath} from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

export async function generateBundledMiniapps() {
  const projectRoot = path.resolve(__dirname, "..")
  const miniappsDir = path.join(projectRoot, "assets", "miniapps")
  const outDir = path.join(projectRoot, "src", "generated")
  const outFile = path.join(outDir, "bundledMiniapps.ts")

  const zips = (await readdir(miniappsDir)).filter((f) => f.toLowerCase().endsWith(".zip")).sort()

  const bundleIdentities = zips.map((name) => {
    const match = /^(.+)-(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?)\.zip$/.exec(name)
    if (!match) throw new Error(`Bundled miniapp ${name} must be named <packageName>-<semver>.zip`)
    return {packageName: match[1], version: match[2]}
  })
  const packageNames = bundleIdentities.map(({packageName}) => packageName)
  const publisherFingerprints = await Promise.all(
    zips.map(async (name, index) => {
      const archive = await JSZip.loadAsync(await readFile(path.join(miniappsDir, name)))
      const entry = archive.file("META-INF/MENTRA.SIG")
      if (!entry) throw new Error(`Bundled miniapp ${name} has no META-INF/MENTRA.SIG`)
      const envelope = JSON.parse(await entry.async("string"))
      const x = envelope?.publicKeyJwk?.x
      if (envelope?.schemaVersion !== 1 || envelope?.algorithm !== "Ed25519" || typeof x !== "string") {
        throw new Error(`Bundled miniapp ${name} has an invalid publisher signature envelope`)
      }
      const raw = Buffer.from(x, "base64url")
      if (raw.byteLength !== 32) throw new Error(`Bundled miniapp ${name} has an invalid Ed25519 public key`)
      const fingerprint = `sha256:${createHash("sha256").update(raw).digest("hex")}`
      if (envelope.publisherKeyFingerprint !== fingerprint) {
        throw new Error(`Bundled miniapp ${name} publisher fingerprint does not match its public key`)
      }
      const files = []
      let manifest
      for (const candidate of Object.values(archive.files)) {
        if (candidate.dir || candidate.name === "META-INF/MENTRA.SIG") continue
        const bytes = await candidate.async("uint8array")
        files.push({path: candidate.name, size: bytes.byteLength, sha256: sha256(bytes)})
        if (candidate.name === "miniapp.json")
          manifest = JSON.parse(new TextDecoder("utf-8", {fatal: true}).decode(bytes))
      }
      const expectedIdentity = bundleIdentities[index]
      if (
        !manifest ||
        manifest.packageName !== expectedIdentity.packageName ||
        manifest.version !== expectedIdentity.version
      ) {
        throw new Error(`Bundled miniapp ${name} filename does not match its miniapp.json identity`)
      }
      files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
      const expectedPayload = {
        packageName: manifest.packageName,
        version: manifest.version,
        manifestSha256: sha256(Buffer.from(canonicalJson(manifest))),
        contentSha256: sha256(Buffer.from(canonicalJson({schemaVersion: 1, files}))),
      }
      if (canonicalJson(envelope.payload) !== canonicalJson(expectedPayload)) {
        throw new Error(`Bundled miniapp ${name} signature payload does not match its contents`)
      }
      const publicKey = createPublicKey({key: envelope.publicKeyJwk, format: "jwk"})
      if (
        !verify(
          null,
          Buffer.from(canonicalJson(envelope.payload)),
          publicKey,
          Buffer.from(envelope.signature, "base64url"),
        )
      ) {
        throw new Error(`Bundled miniapp ${name} publisher signature is invalid`)
      }
      return [packageNames[index], fingerprint]
    }),
  )

  const requires = zips.map((name) => `  require("@assets/miniapps/${name}"),`).join("\n")
  const systemPackages = packageNames.map((packageName) => `  "${packageName}",`).join("\n")
  const publisherKeys = publisherFingerprints
    .map(([packageName, fingerprint]) => `  "${packageName}": "${fingerprint}",`)
    .join("\n")

  const contents = `// AUTO-GENERATED by scripts/generate-bundled-miniapps.mjs — DO NOT EDIT.
// Drop a new zip in assets/miniapps/ and re-run the generator (it runs
// automatically on every build/run via setBuildEnv()).
//
// Each entry is a Metro asset module id (number) for a miniapp bundle shipped
// inside the app binary.

export const BUNDLED_MINIAPPS: number[] = [
${requires}
]

// Build-owned package identities. A manifest cannot request SYSTEM; changing
// this set requires shipping a Mentra App build containing the corresponding
// ZIP asset.
export const BUNDLED_SYSTEM_MINIAPP_PACKAGES = [
${systemPackages}
] as const

// Publisher identities are extracted from the signed ZIPs at build time. The
// host verifies the embedded signature again before activation and requires
// Store updates to retain this build-pinned identity.
export const BUNDLED_SYSTEM_MINIAPP_PUBLISHER_KEYS = {
${publisherKeys}
} as const
`

  // Avoid rewriting (and dirtying git / triggering a Metro reload) when unchanged.
  const existing = await readFile(outFile, "utf8").catch(() => "")
  const rel = path.relative(projectRoot, outFile)
  if (existing !== contents) {
    await mkdir(outDir, {recursive: true})
    await writeFile(outFile, contents)
    console.log(`[generate-bundled-miniapps] wrote ${zips.length} bundle(s) to ${rel}`)
  } else {
    console.log(`[generate-bundled-miniapps] up to date (${zips.length} bundle(s))`)
  }
}

function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`
  return `{${Object.keys(value)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
    .join(",")}}`
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex")
}

// Run directly when invoked as a script. Handles both `node script.mjs` and
// `zx script.mjs` (where argv[1] is zx's path, so we match against argv too).
if (process.argv.some((a) => a.endsWith("generate-bundled-miniapps.mjs"))) {
  await generateBundledMiniapps()
}
