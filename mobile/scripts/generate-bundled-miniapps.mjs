#!/usr/bin/env zx
/**
 * Scans assets/miniapps/ for *.zip bundles and generates
 * src/generated/bundledMiniapps.ts with one literal `require()` per zip. Metro
 * can only bundle assets referenced by a static string-literal require(), so
 * this codegen keeps that list in sync with the directory instead of requiring
 * a manual edit per bundle.
 *
 * Runs automatically from setBuildEnv() (so every build/run script regenerates
 * it), or by hand:
 *   bun run generate-bundled-miniapps
 */
import {readdir, readFile, writeFile, mkdir} from "fs/promises"
import path from "path"
import {fileURLToPath} from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

export async function generateBundledMiniapps() {
  const projectRoot = path.resolve(__dirname, "..")
  const miniappsDir = path.join(projectRoot, "assets", "miniapps")
  const outDir = path.join(projectRoot, "src", "generated")
  const outFile = path.join(outDir, "bundledMiniapps.ts")

  const zips = (await readdir(miniappsDir)).filter((f) => f.toLowerCase().endsWith(".zip")).sort()

  const packageNames = zips.map((name) => {
    const match = /^(.+)-(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?)\.zip$/.exec(name)
    if (!match) throw new Error(`Bundled miniapp ${name} must be named <packageName>-<semver>.zip`)
    return match[1]
  })

  const requires = zips.map((name) => `  require("@assets/miniapps/${name}"),`).join("\n")
  const systemPackages = packageNames.map((packageName) => `  "${packageName}",`).join("\n")

  const contents = `// AUTO-GENERATED by scripts/generate-bundled-miniapps.mjs — DO NOT EDIT.
// Drop a new zip in assets/miniapps/ and re-run the generator (it runs
// automatically on every build/run via setBuildEnv()).
//
// Each entry is a Metro asset module id (number) for a miniapp bundle shipped
// inside the app binary.

export const BUNDLED_MINIAPPS: number[] = [
${requires}
]

// Build-owned package identities. A manifest cannot request SYSTEM; changing
// this set requires shipping a Mentra App build containing the corresponding
// ZIP asset.
export const BUNDLED_SYSTEM_MINIAPP_PACKAGES = [
${systemPackages}
] as const
`

  // Avoid rewriting (and dirtying git / triggering a Metro reload) when unchanged.
  const existing = await readFile(outFile, "utf8").catch(() => "")
  const rel = path.relative(projectRoot, outFile)
  if (existing !== contents) {
    await mkdir(outDir, {recursive: true})
    await writeFile(outFile, contents)
    console.log(`[generate-bundled-miniapps] wrote ${zips.length} bundle(s) to ${rel}`)
  } else {
    console.log(`[generate-bundled-miniapps] up to date (${zips.length} bundle(s))`)
  }
}

// Run directly when invoked as a script. Handles both `node script.mjs` and
// `zx script.mjs` (where argv[1] is zx's path, so we match against argv too).
if (process.argv.some((a) => a.endsWith("generate-bundled-miniapps.mjs"))) {
  await generateBundledMiniapps()
}
