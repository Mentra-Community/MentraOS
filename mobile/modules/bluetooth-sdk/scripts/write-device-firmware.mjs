#!/usr/bin/env node
import {readFileSync, writeFileSync} from "node:fs"
import path from "node:path"
import {fileURLToPath} from "node:url"

/** Additive catalogue: never rewrites Live release metadata or its existing generation path. */
export function validateDeviceFirmware(input) {
  if (
    input?.schemaVersion !== 1 ||
    !input.nimo ||
    !Array.isArray(input.nimo.compatible) ||
    input.nimo.compatible.length > 64
  )
    throw new Error("Invalid device firmware catalogue")
  const compatible = input.nimo.compatible.map(({fullVersion, packedVersion}) => {
    const match =
      typeof fullVersion === "string" &&
      /^FW-VERSION-v(\d+\.\d+\.\d+\.\d+)-[A-Za-z0-9][A-Za-z0-9._-]*$/.exec(fullVersion)
    if (
      !match ||
      match[1] !== packedVersion ||
      fullVersion.length > 512 ||
      packedVersion.split(".").some((part, index) => Number(part) > [15, 127, 511, 4095][index])
    )
      throw new Error("Invalid NIMO compatible firmware identity")
    return {fullVersion, packedVersion}
  })
  let manifest = null
  if (input.nimo.manifest !== null) {
    const candidate = input.nimo.manifest
    const url = new URL(candidate.url)
    if (
      url.protocol !== "https:" ||
      url.username ||
      url.password ||
      url.hash ||
      !/^[0-9a-f]{64}$/.test(candidate.sha256)
    )
      throw new Error("NIMO requires an immutable HTTPS manifest and SHA-256 digest")
    manifest = {url: url.toString(), sha256: candidate.sha256}
  }
  return {schemaVersion: 1, nimo: {manifest, compatible}}
}

export function renderDeviceFirmware(input) {
  const catalogue = validateDeviceFirmware(input)
  const json = JSON.stringify(catalogue)
  return {
    typescript: `/** Generated by scripts/write-device-firmware.mjs. Live metadata is independent. */\nexport const DEVICE_FIRMWARE_CATALOGUE = ${JSON.stringify(
      catalogue,
      null,
      2,
    )} as const\n`,
    swift: `import Foundation\n\n/// Generated by scripts/write-device-firmware.mjs. Live metadata is independent.\nenum GeneratedDeviceFirmware {\n    static let json = ${JSON.stringify(
      json,
    )}\n}\n`,
    kotlin: `package com.mentra.bluetoothsdk\n\n/** Generated by scripts/write-device-firmware.mjs. Live metadata is independent. */\ninternal object GeneratedDeviceFirmware {\n    const val JSON: String = ${JSON.stringify(
      json,
    ).replaceAll("$", "\\$")}\n}\n`,
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  const input = JSON.parse(
    readFileSync(
      process.argv.slice(2).find((arg) => arg !== "--check") ?? path.join(root, "device-firmware.json"),
      "utf8",
    ),
  )
  const output = renderDeviceFirmware(input)
  for (const [language, relative] of Object.entries({
    typescript: "src/generated/deviceFirmware.ts",
    swift: "ios/Source/GeneratedDeviceFirmware.swift",
    kotlin: "android/src/main/java/com/mentra/bluetoothsdk/GeneratedDeviceFirmware.kt",
  })) {
    const file = path.join(root, relative)
    if (process.argv.includes("--check")) {
      if (readFileSync(file, "utf8") !== output[language])
        throw new Error(`Generated firmware catalogue is stale: ${relative}`)
    } else writeFileSync(file, output[language])
  }
}
