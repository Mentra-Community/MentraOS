/**
 * Resolve a provider string (from MODEL_OPTIONS.provider) to its brand icon.
 * Returns null for unknown providers so the caller can fall back.
 */
export function providerIcon(provider: string, className?: string): React.ReactNode {
  switch (provider.toLowerCase()) {
    case 'google':
      return <GoogleIcon className={className} />;
    case 'anthropic':
      return <AnthropicIcon className={className} />;
    case 'openai':
      return <OpenAIIcon className={className} />;
    case 'xai':
      return <XaiIcon className={className} />;
    case 'deepseek':
      return <DeepSeekIcon className={className} />;
    default:
      return null;
  }
}
